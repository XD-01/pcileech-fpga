#ifndef ACAP_IOCTL_WIN_H
#define ACAP_IOCTL_WIN_H

#include "../linux/acap_uapi.h"

#define ACAP_DEVICE_TYPE 0x8000

#define ACAP_IOCTL_GET_INFO \
    CTL_CODE(ACAP_DEVICE_TYPE, 0x801, METHOD_BUFFERED, FILE_READ_ACCESS | FILE_WRITE_ACCESS)
#define ACAP_IOCTL_START \
    CTL_CODE(ACAP_DEVICE_TYPE, 0x802, METHOD_BUFFERED, FILE_WRITE_ACCESS)
#define ACAP_IOCTL_STOP \
    CTL_CODE(ACAP_DEVICE_TYPE, 0x803, METHOD_BUFFERED, FILE_WRITE_ACCESS)

#endif
