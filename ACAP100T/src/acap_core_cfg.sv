// -----------------------------------------------------------------------------
// ACAP-100T : mirror host-visible configuration writes into the PCIe hard block
//
// The host sees the BRAM-backed configuration space.  The 7-series hard block
// has its own internal Type-0 header and BAR decoder which are normally only
// reachable through cfg_mgmt.  In particular BAR0 must be programmed with the
// address the host assigns, otherwise the hard block cannot tag received
// memory requests with the correct BAR-hit vector.
//
// This module serialises those updates through cfg_mgmt and also sets the
// memory-space + bus-master bits once the link is up.
// -----------------------------------------------------------------------------
`timescale 1ns / 1ps
`include "acap_pkg.svh"

module acap_core_cfg (
    input                   clk,
    input                   rst,
    input                   link_up,

    input                   cfg_wr_valid,
    input [9:0]             cfg_wr_addr,
    input [31:0]            cfg_wr_data,
    input [3:0]             cfg_wr_be,

    output logic            cfg_mgmt_wr_en,
    output [9:0]            cfg_mgmt_dwaddr,
    output [31:0]           cfg_mgmt_di,
    output [3:0]            cfg_mgmt_byte_en,
    output                  cfg_mgmt_wr_readonly,
    output                  cfg_mgmt_wr_rw1c_as_rw,
    input                   cfg_mgmt_rd_wr_done
);

    assign cfg_mgmt_wr_readonly   = 1'b0;
    assign cfg_mgmt_wr_rw1c_as_rw = 1'b0;

    // -------------------------------------------------------------------------
    // Request queue: {dwaddr[9:0], byte_en[3:0], data[31:0]}
    // -------------------------------------------------------------------------
    reg [45:0] q [0:3];
    reg [1:0]  wr_ptr;
    reg [1:0]  rd_ptr;
    reg [2:0]  count;

    wire q_full = (count == 3'd4);

    wire host_bar0 = (cfg_wr_addr == 10'h004) &&
                     (cfg_wr_data != 32'hFFFFFFFF) &&
                     (cfg_wr_data != 32'hFFFFF000);
    wire host_cmd  = (cfg_wr_addr == 10'h001);

    localparam [19:0] INIT_WAIT = 20'd625_000;   // 10 ms @ 62.5 MHz
    reg [19:0] init_cnt;
    reg        init_done;
    reg        host_cmd_seen;

    // Dequeue event is generated by the cfg_mgmt serializer below.
    reg  [1:0] state;
    wire       deq = (state == 2'd2) && !cfg_mgmt_rd_wr_done;

    wire enq_host = cfg_wr_valid && (host_bar0 || host_cmd) && !q_full;
    wire init_tick = (init_cnt == INIT_WAIT);
    wire enq_init = !enq_host && !init_done && !host_cmd_seen && link_up &&
                    !q_full && init_tick;

    always @ ( posedge clk ) begin
        if ( rst || !link_up ) begin
            wr_ptr        <= 2'd0;
            count         <= 3'd0;
            init_cnt      <= 20'd0;
            init_done     <= 1'b0;
            host_cmd_seen <= 1'b0;
        end
        else begin
            if ( cfg_wr_valid && host_cmd )
                host_cmd_seen <= 1'b1;

            if ( enq_host ) begin
                q[wr_ptr] <= { cfg_wr_addr, cfg_wr_be, cfg_wr_data };
                wr_ptr    <= wr_ptr + 2'd1;
            end
            else if ( enq_init ) begin
                q[wr_ptr] <= { 10'h001, 4'b0011, 32'h0000_0006 };
                wr_ptr    <= wr_ptr + 2'd1;
                init_done <= 1'b1;
            end
            else if ( !init_done && !host_cmd_seen && link_up && !init_tick ) begin
                init_cnt <= init_cnt + 20'd1;
            end

            count <= count + (enq_host || enq_init ? 3'd1 : 3'd0) - (deq ? 3'd1 : 3'd0);
        end
    end

    // -------------------------------------------------------------------------
    // cfg_mgmt serializer
    // -------------------------------------------------------------------------
    reg [45:0] cur;
    reg [19:0] timeout;

    assign cfg_mgmt_dwaddr  = cur[45:36];
    assign cfg_mgmt_byte_en = cur[35:32];
    assign cfg_mgmt_di      = cur[31:0];

    always @ ( posedge clk ) begin
        if ( rst || !link_up ) begin
            state          <= 2'd0;
            cfg_mgmt_wr_en <= 1'b0;
            cur            <= 46'd0;
            timeout        <= 20'd0;
        end
        else case ( state )
            2'd0: begin // IDLE
                cfg_mgmt_wr_en <= 1'b0;
                timeout        <= 20'd0;
                if ( count != 3'd0 ) begin
                    cur            <= q[rd_ptr];
                    cfg_mgmt_wr_en <= 1'b1;
                    state          <= 2'd1;
                end
            end
            2'd1: begin // WAIT_DONE
                if ( cfg_mgmt_rd_wr_done ) begin
                    cfg_mgmt_wr_en <= 1'b0;
                    state          <= 2'd2;
                end
                else if ( timeout == 20'hFFFFF ) begin
                    cfg_mgmt_wr_en <= 1'b0;
                    state          <= 2'd2;
                end
                else begin
                    timeout <= timeout + 20'd1;
                end
            end
            2'd2: begin // GAP
                if ( !cfg_mgmt_rd_wr_done ) begin
                    rd_ptr <= rd_ptr + 2'd1;
                    state  <= 2'd0;
                end
            end
            default: state <= 2'd0;
        endcase
    end

endmodule
