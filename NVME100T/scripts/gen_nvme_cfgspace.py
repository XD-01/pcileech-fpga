#!/usr/bin/env python3
"""
Generate the NVMe configuration space (COE) and the Identify Controller
data ROM for the NVME100T design.

Identity: vendor 0x1AB2 / device 0x1002, class 0x010802 (NVM Express
controller), BAR0 = 16 kB (register + MSI-X table/PBA), MSI-X with 4
vectors, PCIe Gen2 x1.  Number of namespaces (NN) is 0 on purpose so
Windows binds stornvme.sys without exposing a disk.

Usage:
    python3 gen_nvme_cfgspace.py
"""

import os
import sys

CFG_DWORDS = 1024

VID = 0x1AB2
DID = 0x1002
SUBSYS_ID = 0x1002
SUBSYS_VID = 0x1AB2

cfg = [0] * CFG_DWORDS
mask = [0] * CFG_DWORDS

# ---------------------------------------------------------------------------
# Type-0 header
# ---------------------------------------------------------------------------
cfg[0x00] = (DID << 16) | VID
cfg[0x01] = 0x00100000              # command 0, status: capabilities list
cfg[0x02] = 0x01080201              # class 0x010802, revision 0x01
cfg[0x03] = 0x00000010              # header type 0, cache line 16
cfg[0x04] = 0x00000000              # BAR0, memory 32-bit, 16 kB
for i in range(0x05, 0x0B):
    cfg[i] = 0x00000000
cfg[0x0B] = (SUBSYS_VID << 16) | SUBSYS_ID
cfg[0x0C] = 0x00000000              # expansion ROM disabled
cfg[0x0D] = 0x00000040              # capabilities pointer -> MSI-X @ 0x40
cfg[0x0E] = 0x00000000
cfg[0x0F] = 0x00000100              # INTA#

# ---------------------------------------------------------------------------
# MSI-X capability at 0x40 (next = 0x50), 4 vectors (table size = 3)
# Table  : BAR0 + 0x2000, PBA: BAR0 + 0x3000
# ---------------------------------------------------------------------------
cfg[0x10] = (0x0003 << 16) | (0x50 << 8) | 0x11
cfg[0x11] = 0x00002000
cfg[0x12] = 0x00003000

# ---------------------------------------------------------------------------
# PCI Express capability at 0x50 (next = 0), endpoint, Gen2 x1
# ---------------------------------------------------------------------------
cfg[0x14] = 0x00020010
cfg[0x15] = 0x00008002              # 512-byte MPS, role-based error reporting
cfg[0x16] = 0x00000000
cfg[0x17] = 0x00000012              # link caps: Gen2, x1
cfg[0x18] = 0x00120000              # link status: Gen2 x1
cfg[0x1E] = 0x00000002
cfg[0x1F] = 0x00000002

# ---------------------------------------------------------------------------
# Write mask
# ---------------------------------------------------------------------------
mask[0x01] = 0x0000FFFF
mask[0x03] = 0x0000FFFF
mask[0x04] = 0xFFFFC000             # 16 kB BAR
mask[0x0F] = 0x000000FF
mask[0x10] = 0xC0000000             # MSI-X enable + function mask
mask[0x16] = 0x0000FFFF
mask[0x18] = 0x0000FFFF
mask[0x1D] = 0x0000FFFF
mask[0x1F] = 0x000003FF


def write_coe(path, values):
    words = ["%08X" % v for v in values]
    with open(path, "w", newline="\n") as f:
        f.write("memory_initialization_radix=16;\n")
        f.write("memory_initialization_vector=\n")
        for i in range(0, len(words), 8):
            line = ",".join(words[i:i + 8])
            if i + 8 < len(words):
                line += ","
            f.write(line + "\n")
        f.write(";\n")


def build_identify():
    """Build the 4096-byte Identify Controller structure (little endian)."""
    buf = bytearray(4096)

    def put(off, data):
        buf[off:off + len(data)] = data

    put(0, VID.to_bytes(2, "little"))
    put(2, VID.to_bytes(2, "little"))
    put(4, b"NVME100T".ljust(20, b" "))
    put(24, b"CaptainDMA NVMe Controller".ljust(40, b" "))
    put(64, b"1.0".ljust(8, b" "))
    put(72, b"\x00")
    put(73, bytes([0x00, 0x1A, 0xB2]))
    buf[76] = 0x00                  # CMIC
    buf[77] = 0x00                  # MDTS (no limit)
    put(78, (1).to_bytes(2, "little"))          # CNTLID
    put(80, (0x00010400).to_bytes(4, "little")) # VER 1.4
    put(256, (0).to_bytes(2, "little"))         # OACS
    buf[258] = 3                    # ACL
    buf[259] = 3                    # AERL
    buf[260] = 0                    # FRMW
    buf[261] = 0                    # LPA
    buf[262] = 0                    # ELPE
    buf[263] = 0                    # NPSS
    put(512, (0).to_bytes(4, "little"))         # NN = 0 (no namespaces)
    put(516, (0).to_bytes(2, "little"))         # ONCS
    put(518, (0).to_bytes(2, "little"))         # FUSES
    put(532, (0).to_bytes(4, "little"))         # SGLS
    buf[544] = 0x66                 # SQES: 64 bytes
    buf[545] = 0x44                 # CQES: 16 bytes
    return buf


def write_identify_sv(path):
    buf = build_identify()
    groups = []
    for i in range(0, 4096, 16):
        groups.append(int.from_bytes(buf[i:i + 16], "little"))
    lines = []
    lines.append("// Generated by scripts/gen_nvme_cfgspace.py - do not edit.")
    lines.append("`timescale 1ns / 1ps")
    lines.append("")
    lines.append("module nvme_ident_data(")
    lines.append("    input  [7:0]   idx,")
    lines.append("    output reg [127:0] data")
    lines.append(");")
    lines.append("")
    lines.append("    always @ * begin")
    lines.append("        case ( idx )")
    for i, w in enumerate(groups):
        if w != 0:
            lines.append("            8'h%02X: data = 128'h%032X;" % (i, w))
    lines.append("            default: data = 128'h00000000000000000000000000000000;")
    lines.append("        endcase")
    lines.append("    end")
    lines.append("")
    lines.append("endmodule")
    lines.append("")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.normpath(os.path.join(here, ".."))
    write_coe(os.path.join(root, "ip", "pcileech_cfgspace.coe"), cfg)
    write_coe(os.path.join(root, "ip", "pcileech_cfgspace_writemask.coe"), mask)
    write_identify_sv(os.path.join(root, "src", "nvme_ident_data.sv"))
    print("NVMe config space + Identify ROM generated")
    print("VID:DID = %04X:%04X  class = 0x010802  BAR0 = 16 kB" % (VID, DID))
    return 0


if __name__ == "__main__":
    sys.exit(main())
